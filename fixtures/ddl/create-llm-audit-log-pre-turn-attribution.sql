CREATE TABLE `llm_audit_log` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `user_id` int unsigned NOT NULL COMMENT 'Admin user who confirmed the write',
  `system` varchar(16) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'capy' COMMENT 'Producing product: capy | appnext',
  `conversation_uuid` char(36) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'FK to capy_conversations.uuid (nullable for pre-M1 writes)',
  `tool_use_id` varchar(64) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'Anthropic tool_use block ID (Capy only; NULL for assistant internal tools)',
  `tool_name` varchar(128) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL COMMENT 'Endpoint tool name',
  `endpoint_path` varchar(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'Full API path called (Capy only; NULL for assistant internal tools)',
  `http_method` varchar(10) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci NOT NULL DEFAULT 'POST',
  `request_params` longtext CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL COMMENT 'Tool call input parameters',
  `response_code` smallint unsigned DEFAULT NULL,
  `response_summary` text CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci COMMENT 'Truncated response (max 10KB)',
  `success` tinyint unsigned NOT NULL DEFAULT '0',
  `execution_time_ms` int unsigned DEFAULT NULL,
  `write_chain_parent_id` bigint unsigned DEFAULT NULL COMMENT 'Self-FK for chained writes',
  `is_auto_confirmed` tinyint unsigned NOT NULL DEFAULT '0',
  `batch_id` char(36) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'Groups writes belonging to the same batch',
  `batch_index` smallint unsigned DEFAULT NULL COMMENT 'Position within batch (0-indexed)',
  `batch_total` smallint unsigned DEFAULT NULL COMMENT 'Total items in batch',
  `is_active` tinyint unsigned NOT NULL DEFAULT '1',
  `create_time` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_batch` (`batch_id`),
  KEY `idx_chain_parent` (`write_chain_parent_id`),
  KEY `idx_conversation` (`conversation_uuid`),
  KEY `idx_system_tool` (`system`,`tool_name`,`create_time`),
  KEY `idx_tool` (`tool_name`,`create_time`),
  KEY `idx_user` (`user_id`,`create_time`),
  CONSTRAINT `llm_audit_log_request_params` CHECK (json_valid(`request_params`))
);
